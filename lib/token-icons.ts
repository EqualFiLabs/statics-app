import tokenLogoAssets from "@/lib/generated/token-logo-assets.json";
import chainTokenLogos from "@/lib/generated/chain-token-logos.json";

export const ETH_TOKEN_ICON_URI = "/icons/eth.svg";
export const SOL_TOKEN_ICON_URI = "/icons/sol.svg";

export function getNativeTokenLogoURI(symbol: string | undefined) {
  const normalized = symbol?.trim().toUpperCase();
  return normalized === "ETH"
    ? ETH_TOKEN_ICON_URI
    : normalized === "SOL"
      ? SOL_TOKEN_ICON_URI
      : undefined;
}

export function allowedTokenLogoURI(value: string | undefined) {
  if (!value) return null;
  if (value.startsWith("/icons/") || value.startsWith("/assets/token-logos/")) return value;
  return (tokenLogoAssets.logos as Readonly<Record<string, string>>)[value] ?? null;
}

/**
 * Reviewed logos for tokens on chains the Uniswap list does not cover (Robinhood), matched by
 * chain and address only, never by symbol. Generated by scripts/generate-chain-token-logos.mjs.
 */
export function chainTokenLogoURI(chainId: number, address: string): string | undefined {
  return (chainTokenLogos.logos as Readonly<Record<string, string>>)[
    `${chainId}:${address.toLowerCase()}`
  ];
}
