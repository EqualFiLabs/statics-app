#!/usr/bin/env node
/**
 * Generates a checked-in deployment manifest from a live deployment.
 *
 * Usage:
 *   node scripts/generate-deployment-manifest.mjs \
 *     --rpc https://rpc.testnet.chain.robinhood.com \
 *     --addresses ../statics/deployments/robinhood-testnet.json \
 *     --commit <40-char protocol commit> \
 *     --public-commit <40-char public repository commit> \
 *     --source-repository https://github.com/EqualFiLabs/statics \
 *     --deployment-artifact deployments/robinhood-testnet-46630-statics.json \
 *     --network "Robinhood Chain Testnet" \
 *     --start-block 12345 \
 *     --weth-profile 1
 *
 * Every runtime code hash is read from the chain rather than copied from build
 * output, so the manifest records what is deployed rather than what was meant
 * to be. Addresses come from the protocol's own deploy artifact, so nobody
 * types one by hand.
 *
 * The result is written to deployments/<chainId>.json and the registry in
 * deployments/manifests.ts is rewritten to match the directory. Both are meant
 * to be committed: pointing the app at new contracts should be a reviewable
 * diff.
 */

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createPublicClient, http, getAddress, keccak256 } from "viem";

const siteRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const deploymentsDir = resolve(siteRoot, "deployments");
const SCHEMA_VERSION = 6;

const DOLLAR = ["diamond", "core", "gateway", "dollar", "risk", "weth", "oracle"];
const LIQUIDITY = [
  "poolManager",
  "positionManager",
  "permit2",
  "swapFeeHook",
  "liquidityManager",
  "stateView",
  "quoter",
  "universalRouter",
];

function arg(name, { required = true } = {}) {
  const index = process.argv.indexOf(`--${name}`);
  if (index === -1 || !process.argv[index + 1]) {
    if (required) throw new Error(`Missing required --${name}`);
    return null;
  }
  return process.argv[index + 1];
}

/**
 * Pulls a contract's deployed runtime code and hashes it.
 *
 * An address with no code is the failure this is here to catch: it means the
 * artifact points somewhere nothing was deployed, which would otherwise only
 * surface as a confusing revert in the app.
 */
async function runtimeCodeHash(client, name, address) {
  const code = await client.getCode({ address });
  if (!code || code === "0x") {
    throw new Error(`${name} at ${address} has no deployed code on this chain.`);
  }
  return keccak256(code);
}

async function entryFor(client, name, address) {
  const checksummed = getAddress(address);
  return {
    address: checksummed,
    runtimeCodeHash: await runtimeCodeHash(client, name, checksummed),
  };
}

function address(value) {
  return typeof value === "string" ? value : value?.address;
}

function pick(source, name) {
  const value = address(source?.[name]);
  if (!value) throw new Error(`Address artifact is missing "${name}".`);
  return value;
}

/** Rewrites the registry from the directory, so the two cannot drift. */
function writeRegistry() {
  const files = readdirSync(deploymentsDir)
    .filter((file) => /^\d+\.json$/.test(file))
    .sort((left, right) => Number.parseInt(left, 10) - Number.parseInt(right, 10));

  const imports = files
    .map((file) => `import chain${file.replace(".json", "")} from "./${file}";`)
    .join("\n");
  const entries = files
    .map((file) => {
      const id = file.replace(".json", "");
      return `  ${id}: chain${id} as DeploymentManifest,`;
    })
    .join("\n");

  writeFileSync(
    resolve(deploymentsDir, "manifests.ts"),
    `/**
 * Every checked-in deployment manifest, keyed by chain id.
 *
 * Generated by scripts/generate-deployment-manifest.mjs from the contents of
 * this directory. Do not edit by hand: rerun the generator so the registry and
 * the JSON beside it cannot fall out of step.
 *
 * Empty is a valid state: it means no network has a reviewed deployment yet,
 * and the app reports every chain as unconfigured rather than guessing.
 */
import type { DeploymentManifest } from "@/lib/dollar/manifest";
${imports ? `\n${imports}\n` : ""}
export const deploymentManifests: Readonly<Record<number, DeploymentManifest>> = {
${entries}
};
`
  );
  return files;
}

async function main() {
  const rpcUrl = arg("rpc");
  const addressesPath = arg("addresses");
  const commit = arg("commit");
  const publicCommit = arg("public-commit");
  const sourceRepository = arg("source-repository");
  const deploymentArtifact = arg("deployment-artifact");
  const network = arg("network");
  const startBlock = arg("start-block");
  const wethProfile = arg("weth-profile");
  const peggedProfile = arg("pegged-profile", { required: false });

  for (const [flag, value] of [
    ["commit", commit],
    ["public-commit", publicCommit],
  ]) {
    if (!/^[a-f0-9]{40}$/i.test(value)) {
      throw new Error(`--${flag} must be a full 40-character Git commit.`);
    }
  }
  const sourceUrl = new URL(sourceRepository);
  if (sourceUrl.protocol !== "https:" || sourceUrl.username || sourceUrl.password) {
    throw new Error("--source-repository must be a credential-free HTTPS URL.");
  }
  if (
    !/^(?:deployments\/[a-z0-9][a-z0-9._/-]*\.json|deployment\.md)$/i.test(deploymentArtifact) ||
    deploymentArtifact.includes("..")
  ) {
    throw new Error("--deployment-artifact must name a public deployment record.");
  }
  for (const [flag, value] of [
    ["start-block", startBlock],
    ["weth-profile", wethProfile],
  ]) {
    if (!/^\d+$/.test(value)) throw new Error(`--${flag} must be a non-negative integer.`);
  }

  const artifact = JSON.parse(readFileSync(resolve(process.cwd(), addressesPath), "utf8"));
  const client = createPublicClient({ transport: http(rpcUrl) });
  const chainId = await client.getChainId();
  const artifactChainId = artifact.network?.chainId ?? artifact.chainId;
  if (artifactChainId !== undefined && Number(artifactChainId) !== chainId) {
    throw new Error(
      `Artifact declares chain ${artifactChainId} but ${rpcUrl} reports ${chainId}. ` +
        "Refusing to write a manifest that names the wrong network."
    );
  }

  const rehearsal = Boolean(artifact.protocol?.staticsDiamond);
  const contractsSource = rehearsal
    ? {
        diamond: artifact.protocol.staticsDiamond,
        core: artifact.protocol.coreDiamond,
        gateway: artifact.protocol.staticsDiamond,
        dollar: artifact.protocol.usdStx,
        risk: artifact.protocol.riskShares,
        weth: artifact.dependencies?.weth,
        oracle: artifact.protocol.coreEthUsdOracle,
      }
    : {
        diamond: artifact.contracts?.staticsDiamond,
        core: artifact.contracts?.staticsDollarCoreDiamond,
        gateway: artifact.contracts?.staticsDiamond,
        dollar: artifact.contracts?.staticsDollar,
        risk: artifact.contracts?.staticsDollarRiskShares,
        weth: artifact.externalDependencies?.weth,
        oracle: artifact.contracts?.staticsDollarOracle,
      };
  const contracts = {};
  for (const name of DOLLAR) {
    contracts[name] = await entryFor(client, name, pick(contractsSource, name));
  }

  const genesisSource = rehearsal
    ? {
        token: artifact.genesisReplica?.statics,
        collection: artifact.genesisReplica?.genesisCollection,
        renderer: artifact.genesisReplica?.genesisRenderer,
        avatarSvg: artifact.genesisReplica?.avatarSvg,
        activationRegistry: artifact.genesisReplica?.activationRegistry,
      }
    : {
        token: artifact.contracts?.staticsToken,
        collection: artifact.contracts?.genesisNFT,
        renderer: artifact.contracts?.genesisRenderer,
        avatarSvg: artifact.contracts?.avatarSVG,
        activationRegistry: artifact.contracts?.genesisActivationRegistry,
      };
  const genesis = {
    token: await entryFor(client, "staticsToken", pick(genesisSource, "token")),
    collection: await entryFor(client, "genesisNFT", pick(genesisSource, "collection")),
    renderer: await entryFor(client, "genesisRenderer", pick(genesisSource, "renderer")),
    avatarSvg: await entryFor(client, "avatarSVG", pick(genesisSource, "avatarSvg")),
    activationRegistry: await entryFor(
      client,
      "genesisActivationRegistry",
      pick(genesisSource, "activationRegistry")
    ),
  };

  const liquiditySource = rehearsal
    ? {
        poolManager: artifact.dependencies?.poolManager,
        positionManager: artifact.dependencies?.positionManager,
        permit2: artifact.dependencies?.permit2,
        swapFeeHook: artifact.protocol?.swapFeeHook,
        liquidityManager: artifact.protocol?.liquidityManager,
        stateView: artifact.dependencies?.stateView,
        quoter: artifact.dependencies?.quoter,
        universalRouter: artifact.dependencies?.universalRouter,
      }
    : {
        poolManager: artifact.externalDependencies?.poolManager,
        positionManager: artifact.externalDependencies?.positionManager,
        permit2: artifact.externalDependencies?.permit2,
        swapFeeHook: artifact.contracts?.swapFeeHook,
        liquidityManager: artifact.contracts?.liquidityManager,
        stateView: artifact.externalDependencies?.stateView,
        quoter: artifact.externalDependencies?.quoter,
        universalRouter: artifact.externalDependencies?.universalRouter,
      };
  const liquidity = {};
  for (const name of LIQUIDITY) {
    liquidity[name] = await entryFor(client, name, pick(liquiditySource, name));
  }

  let pegged = null;
  if (peggedProfile) {
    pegged = {
      profileId: peggedProfile,
      collateral: await entryFor(
        client,
        "usdg",
        rehearsal
          ? pick(artifact.peggedProfile, "collateralToken")
          : pick(artifact.testnetFixtures, "mockUsdg")
      ),
      oracle: await entryFor(
        client,
        "usdgOracle",
        rehearsal
          ? pick(artifact.peggedProfile, "oracle")
          : pick(artifact.testnetFixtures, "usdgOracle")
      ),
    };
  }

  const faucetAddress = address(rehearsal ? artifact.faucet : artifact.testnetFixtures?.faucet);
  const faucet = faucetAddress ? await entryFor(client, "faucet", faucetAddress) : null;

  let morpho = null;
  if (rehearsal && artifact.morphoIntegration) {
    const integration = artifact.morphoIntegration;
    morpho = {
      protocol: await entryFor(client, "morpho", pick(integration, "morpho")),
      irm: await entryFor(client, "morphoIrm", pick(integration, "irm")),
      lltv: String(integration.lltv),
      markets: await Promise.all(
        [
          [integration.staticsMarket, "statics"],
          [integration.basketMarket, "basket"],
        ].map(async ([market, kind]) => ({
          marketId: market.marketId,
          collateral: getAddress(market.collateralToken),
          oracle: await entryFor(client, `${kind}MorphoOracle`, market.oracle),
          kind,
          ...(kind === "basket" ? { basketId: String(market.basketId) } : {}),
        }))
      ),
    };
  }

  const manifest = {
    schemaVersion: SCHEMA_VERSION,
    deploymentId: String(artifact.deploymentId ?? `${chainId}-${commit.slice(0, 12)}`),
    network,
    chainId,
    deploymentStartBlock: startBlock,
    wethProfileId: wethProfile,
    protocolCommit: commit.toLowerCase(),
    source: {
      repository: sourceUrl.toString().replace(/\/$/u, ""),
      publicCommit: publicCommit.toLowerCase(),
      deploymentArtifact,
      recordedDeploymentCommit: commit.toLowerCase(),
    },
    generatedAt: new Date().toISOString(),
    contracts,
    genesis,
    liquidity,
    pegged,
    faucet,
    morpho,
  };

  const target = resolve(deploymentsDir, `${chainId}.json`);
  writeFileSync(target, `${JSON.stringify(manifest, null, 2)}\n`);
  const files = writeRegistry();

  console.log(`Wrote deployments/${chainId}.json`);
  console.log(`Registry now lists: ${files.join(", ") || "(none)"}`);
  console.log("Review and commit both files.");
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
